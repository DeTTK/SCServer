package vr;
import java.util.*;
import static vr.NativeAccess.*;

/** Dispatch controller buttons through native bindings, including press/release and cooldowns. */
final class NativeControls {
    private Object dispatcher;
    private final Map<String,Object> bindings=new HashMap<>();
    private Object fireComponent,fireHandler,fireConfig;
    private boolean firing;
    private final Map<Object,Integer> pressed=new LinkedHashMap<>();
    void selectWeapon(Object game,Object equipment,Object slot)throws Exception {
        call(equipment,"protected","void",((Enum<?>)slot).ordinal());
        // The promoted controller updates its local slot, but its network event
        // callback 276406255.do is empty. Send the stock nullable hand address
        // on the same reliable stream, before opening the new VR reload cycle.
        Object selected=call(equipment,"try","920235447");
        Object holder=call(get(equipment,"class"),"boolean","849613593",selected);
        int container=((Number)call(holder,"protected","int")).intValue();
        Object address=type("949164803").getConstructor(int.class,int.class,int.class).newInstance(0,container,0);
        Object packet=type("753855485").getConstructor(type("949164803")).newInstance(address);
        Object connection=call(game,"transient","1219970978");
        if(connection==null)throw new IllegalStateException("Weapon selection has no game connection");
        Object envelope=type("385693344").getConstructor(type("499058674")).newInstance(packet);
        call(connection,"else","void",envelope);
    }
    Object movement(ControllerIntent.Move move,Object original)throws Exception {
        Object intent=type("1899091998").getConstructor().newInstance();
        set(intent,"int",move.direction());set(intent,"case",get(type("1785380642"),move.gait()));
        set(intent,"finally",move.jump());set(intent,"continue",move.crouchPressed());set(intent,"goto",move.crouch());
        // Keep queued native actions generated by the injected controller bindings.
        set(intent,"long",get(original,"long"));
        return intent;
    }
    private void selectDispatcher(Object game)throws Exception {
        Object next=call(call(game,"transient","1855282131"),"package","1822220185");
        if(dispatcher!=null&&dispatcher!=next)release();
        dispatcher=next;
    }
    Object namedBinding(Object game,String name)throws Exception {
        selectDispatcher(game);
        Object known=bindings.get(name);
        if(known!=null)return known;
        for(Object key:((Map<?,?>)get(dispatcher,"const")).keySet()){
            if(type("1726668630").isInstance(key)&&name.equals(get(key,"for"))){
                bindings.put(name,key);
                return key;
            }
        }
        return null;
    }
    boolean pulse(Object game,String... names)throws Exception {
        for(String name:names){
            Object key=namedBinding(game,name);
            if(key==null)continue;
            binding(game,key,true);
            binding(game,key,false);
            return true;
        }
        return false;
    }
    void throwBolt(Object game,VrBoltGesture.Throw intent)throws Exception {
        Object connection=call(game,"transient","1219970978");
        if(connection==null)return;
        Object packet=type("szmods.bridge.VrBolt").getConstructor(byte[].class).newInstance((Object)intent.bytes());
        Object envelope=type("385693344").getConstructor(type("499058674")).newInstance(packet);
        call(connection,"else","void",envelope);
    }
    void binding(Object game,Object binding,boolean down)throws Exception {
        selectDispatcher(game);
        boolean was=pressed.containsKey(binding);if(was==down)return;
        Object state=((Map<?,?>)get(dispatcher,"const")).get(binding);if(state==null)throw new IllegalStateException("Native binding not registered");
        int code=was?pressed.get(binding):((Number)call(binding,"void","int")).intValue();
        if(down)pressed.put(binding,code);
        try{call(dispatcher,"szmods$vr$float","void",state,code,down?1:0,true);}
        finally{if(!down)pressed.remove(binding);}
    }
    void fire(Object game,boolean down)throws Exception {
        Object actor=get(game,"e"),component=actor==null?null:call(type("1810277368"),"static","1810277368",actor);
        Object config=component==null?null:call(component,"this","1745367406");
        if(component!=fireComponent){
            if(fireConfig!=null)mouse("UP");fireComponent=component;fireConfig=config;fireHandler=get(type("1378012157"),"float");firing=false;
            // The native mouse handler owns charge/burst latches independently of bindings.
            if(fireConfig!=null)mouse("UP");
        }else fireConfig=config;
        if(config==null){firing=false;return;}
        if(down){mouse(firing?"PRESSED":"DOWN");firing=true;}
        else if(firing){try{mouse("UP");}finally{firing=false;}}
    }
    private void mouse(String phase)throws Exception {
        if(fireHandler==null||fireConfig==null||fireComponent==null)return;
        Object state=get(type("84240326"),phase);
        if(phase.equals("UP")){
            // Release the previous component even after a weapon/player change.
            call(fireHandler,"byte","void",fireConfig,state,fireComponent);return;
        }
        Object event=type("160172807").getConstructor(type("614806840"),type("84240326")).newInstance(get(type("614806840"),"LEFT"),state);
        call(fireHandler,"szmods$vr$mouse","void",event);
    }
    void release()throws Exception {
        Exception failure=null;
        try{if(fireConfig!=null)mouse("UP");}catch(Exception e){failure=e;}
        finally{firing=false;fireComponent=fireHandler=fireConfig=null;}
        for(var entry:new ArrayList<>(pressed.entrySet()))try{
            Object state=((Map<?,?>)get(dispatcher,"const")).get(entry.getKey());if(state!=null)call(dispatcher,"szmods$vr$float","void",state,entry.getValue(),0,true);
        }catch(Exception e){failure=e;}
        pressed.clear();bindings.clear();dispatcher=null;if(failure!=null)throw failure;
    }
}
